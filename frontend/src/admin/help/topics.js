// Flattened text per topic, for search.
export function topicText(t) {
  return [
    t.title,
    t.summary,
    t.what,
    t.access,
    ...(t.steps || []).flatMap((s) => [s.title, s.detail]),
    ...(t.actions || []),
    ...(t.fields || []).flatMap((f) => [f.name, f.description]),
    ...(t.outcomes || []),
    ...(t.problems || []).flatMap((p) => [p.problem, p.fix]),
    ...(t.tips || []),
    ...(t.warnings || []),
    ...(t.limits || []),
  ]
    .filter(Boolean)
    .join(" \n ");
}
